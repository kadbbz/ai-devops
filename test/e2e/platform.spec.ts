import playwright from '../../package/node_modules/@playwright/test/index.js'
const { test, expect } = playwright
async function login(page: any, username: string) {
  await page.goto('/')
  await page.getByLabel('账号', { exact: true }).fill(username)
  await page.getByLabel('密码', { exact: true }).fill('test-password-12345')
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await expect(page.getByText('项目与我的待办')).toBeVisible()
  await page.getByRole('link', { name: '内部知识库' }).click()
}
test('负责人通过页面完成变更、需求设计确认和上下文下载', async ({ page }) => {
  await login(page, 'owner')
  await expect(page.getByText('Phoenix 资源型项目 P0 试点')).toBeVisible()
  await expect(page.getByText('变化可视化', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '新建变更' }).click()
  await page.getByLabel('一句话描述变更').fill('端到端验收：空结果直接提示')
  await page.getByRole('button', { name: '保存', exact: true }).click()
  await expect(page.getByRole('tab', { name: '目标与验收' })).toBeVisible()
  await page.getByRole('button', { name: '编辑需求' }).click()
  await page.getByLabel('验收标准（每行一条）').fill('空结果调用次数为零\n有结果继续问答')
  await page.getByRole('button', { name: '保存', exact: true }).click()
  await page.getByRole('button', { name: '确认需求', exact: true }).click()
  await page.getByRole('button', { name: '确认执行' }).click()
  await expect(page.getByText('v2 · 人工已确认')).toBeVisible()
  await page.getByRole('tab', { name: '设计与影响' }).click()
  await page.getByRole('button', { name: '编辑设计' }).click()
  await page.getByLabel('设计概要').fill('检索后判断集合为空，返回提示并跳过模型调用')
  await page.getByLabel('影响范围（每行一条）').fill('ask 逻辑')
  await page.getByRole('button', { name: '保存', exact: true }).click()
  await page.getByRole('button', { name: '确认设计', exact: true }).click()
  await page.getByRole('button', { name: '确认执行' }).click()
  await page.getByRole('tab', { name: '开发与 PR' }).click()
  await page.getByRole('button', { name: '生成上下文包' }).click()
  await page.getByRole('button', { name: '保存', exact: true }).click()
  await expect(page.getByRole('link', { name: '下载上下文包' })).toBeVisible()
  const download = page.waitForEvent('download')
  await page.getByRole('link', { name: '下载上下文包' }).click()
  expect((await download).suggestedFilename()).toContain('context')
})
test('干系人看到项目和证据，无法执行写操作', async ({ page }) => {
  await login(page, 'stakeholder')
  await expect(page.getByRole('button', { name: '新建变更' })).toHaveCount(0)
  await page.getByRole('menuitem', { name: '变更工作台' }).click()
  await expect(page.getByRole('button', { name: '编辑需求' })).toHaveCount(0)
  await expect(page.getByRole('button', { name: '确认需求', exact: true })).toBeDisabled()
  await page.getByRole('menuitem', { name: '项目审计' }).click()
  await expect(page.getByRole('button', { name: '查询', exact: true })).toBeVisible()
})
test('审计员可查询全局审计，窄屏不产生页面水平溢出', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await login(page, 'auditor')
  await page.getByRole('link', { name: '全局审计' }).click()
  await page.getByRole('textbox', { name: '动作', exact: true }).fill('auth.login')
  await page.getByRole('button', { name: '查询', exact: true }).click()
  await expect(page.getByText('哈希链校验通过').first()).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
})
test('人工报告附件上传后可见并可下载', async ({ page }) => {
  await login(page, 'member')
  await page.getByRole('menuitem', { name: '测试与证据' }).click()
  await page
    .getByLabel('选择报告附件')
    .setInputFiles({
      name: '真实上传测试报告.txt',
      mimeType: 'text/plain',
      buffer: Buffer.from('AC-01：已人工执行，模型调用次数为 0。')
    })
  await expect(page.getByText('真实上传测试报告.txt')).toBeVisible()
  const download = page.waitForEvent('download')
  await page.getByRole('link', { name: '下载证据' }).click()
  expect((await download).suggestedFilename()).toBe('真实上传测试报告.txt')
})
